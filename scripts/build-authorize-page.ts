/**
 * Bundles the React authorize page into a single self-contained script and
 * writes it to a generated module that the Vite plugin inlines into the page.
 * Consumers of the plugin therefore need neither React nor AutoForm.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build, type Rolldown } from 'vite';

const root = fileURLToPath(new URL('..', import.meta.url));
const outputFile = fileURLToPath(
  new URL('../src/authorize-page/bundle.generated.ts', import.meta.url),
);

const result = await build({
  root,
  configFile: false,
  logLevel: 'warn',
  define: {
    'process.env.NODE_ENV': JSON.stringify('production'),
  },
  oxc: {
    jsx: { runtime: 'automatic' },
  },
  build: {
    write: false,
    minify: true,
    target: 'es2022',
    lib: {
      entry: 'src/authorize-page/app/main.tsx',
      formats: ['iife'],
      name: 'mockOidcAuthorizePage',
      fileName: () => 'authorize-page.js',
    },
    rolldownOptions: {
      onLog(level, log, handler) {
        if (log.code !== 'MODULE_LEVEL_DIRECTIVE') {
          handler(level, log);
        }
      },
      output: {
        codeSplitting: false,
      },
    },
  },
});

const outputs = (Array.isArray(result) ? result : [result]) as Rolldown.RolldownOutput[];
const chunks = outputs
  .flatMap((output) => output.output)
  .filter((item): item is Rolldown.OutputChunk => item.type === 'chunk');

if (chunks.length !== 1) {
  throw new Error(`Expected a single authorize page chunk, got ${chunks.length}`);
}

const script = chunks[0]!.code.replace(/<\/(script)/gi, '<\\/$1');

await writeFile(
  outputFile,
  `// Generated by scripts/build-authorize-page.ts. Do not edit.\nexport const authorizePageScript: string = ${JSON.stringify(script)};\n`,
);

console.log(
  `Wrote ${fileURLToPath(new URL(outputFile, 'file:'))} (${(script.length / 1024).toFixed(1)} KiB)`,
);
